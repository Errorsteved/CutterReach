function row = summaryRow(label,design,b,t,other)
%SUMMARYROW Paired dexterity is compared only over identical reached target IDs.
ok = t.nFree>0; common = ok & other.nFree>0;
row = table(string(label),string(design),b.arm,diff(b.limits(5,:)),height(t), ...
    nnz(t.nPose),nnz(ok),mean(ok),sum(t.eta,'omitnan')/height(t), ...
    mean(t.eta(ok)),nnz(common),mean(t.eta(common)), ...
    'VariableNames',{'Set','Design','Arm_m','Stroke_m','Cutters','BoundedCutters', ...
    'Reached','Rate','MeanEtaAll','MeanEtaReached','CommonCutters','MeanEtaCommon'});
end
